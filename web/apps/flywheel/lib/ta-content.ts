export function taBatch(s: string) {
  return s.replace("Launch", "தொடக்கம்").replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, (m) => MONTHS[m]);
}

export function taPrice(p: Programme) {
  if (p.priceStatus === "Free") return "இலவசம்";
  if (p.price === "Quoted per organisation") return "நிறுவனத்துக்கு ஏற்ப விலை";
  return p.price.replace("lakh", "லட்சம்");
}

export function taLanguage(lang: string) {
  if (lang.includes("Tamil support")) return "ஆங்கிலம்; தமிழ் உதவி";
  if (lang.includes("Tamil")) return "தமிழ் மற்றும் ஆங்கிலம்";
  return "ஆங்கிலம்";
}

